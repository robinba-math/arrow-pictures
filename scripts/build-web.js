// Bundles the puzzle library into web/puzzles.js, theme by theme, in the
// order puzzles/library.json gives. Refuses to bundle a puzzle that fails
// the checker, so the app only ever ships valid puzzles, and refuses a theme
// that doesn't climb from 1 star to 5.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { checkPuzzle } from '../engine/index.js';

const lib = JSON.parse(readFileSync('puzzles/library.json', 'utf8'));
let failed = 0;

function bundle(t, archive) {
  const files = readdirSync(`puzzles/${t.dir}`).filter((f) => f.endsWith('.json'))
    .sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));
  const puzzles = [];
  const ratings = [];
  for (const f of files) {
    const json = JSON.parse(readFileSync(`puzzles/${t.dir}/${f}`, 'utf8'));
    const r = checkPuzzle(json);
    if (!r.ok) {
      failed++;
      console.error(`FAIL ${t.dir}/${f}: ${r.errors.map((e) => e.message).join('; ')}`);
      continue;
    }
    puzzles.push(json);
    ratings.push(r.difficulty.rating);
  }
  const climbs = ratings[0] === 1 && ratings.at(-1) === 5 && ratings.every((n, i) => i === 0 || n >= ratings[i - 1]);
  if (!archive && !climbs) {
    failed++;
    console.error(`FAIL ${t.title}: stars must climb from 1 to 5, got ${ratings.join(' ')}`);
  }
  console.log(`${t.title}: ${ratings.map((n) => '★'.repeat(n)).join(' ')}`);
  return { id: t.dir.replace(/\//g, '-'), title: t.title, blurb: t.blurb, archive, puzzles };
}

const themes = [...lib.themes.map((t) => bundle(t, false)), ...lib.archive.map((t) => bundle(t, true))];
if (failed) process.exit(1);
writeFileSync('web/puzzles.js', `// Generated by scripts/build-web.js from puzzles/library.json. Do not edit.\nexport default ${JSON.stringify(themes, null, 2)};\n`);
console.log(`bundled ${themes.reduce((s, t) => s + t.puzzles.length, 0)} puzzles in ${themes.length} themes into web/puzzles.js`);
